import sys
import tomllib

REPO_ROOT = Path(__file__).resolve().parent.parent

AGENT_FRONTMATTER = {
    "supervisor": (
        "---\n"
        "name: slp-supervisor\n"
        'description: "SLP governance, cross-workspace coordination, and lifecycle oversight through Paseo."\n'
        "mainAgent: true\n"
        "subagent: false\n"
        "model: inherit\n"
        "---\n\n"
    ),
    "lead": (
        "---\n"
        "name: slp-lead\n"
        'description: "SLP lane planning, briefs, integration, acceptance, and Peer coordination through Paseo."\n'
        "mainAgent: true\n"
        "subagent: false\n"
        "model: inherit\n"
        "---\n\n"
    ),
    "peer": (
        "---\n"
        "name: slp-peer\n"
        'description: "SLP scoped implementation, investigation, and independent review under a Lead."\n'
        "mainAgent: true\n"
        "subagent: false\n"
        "model: inherit\n"
        "---\n\n"
    ),
}

FORBIDDEN_PEER_REFS = (
    "shared/README.md",
    "handoff.md",
    "anti-patterns.md",
    "audit.md",
    "catalog.md",
    "structural-antipatterns.md",
)

STALE_PROVIDER_TOKENS = ("pi-peer", "deepseek-v4-1-flash")


def load_providers(repo_root: Path = REPO_ROOT) -> dict:
    return json.loads((repo_root / "paseo" / "providers.json").read_text(encoding="utf-8"))


def format_provider_menu(providers_doc: dict, provider_ids: list[str]) -> str:
    providers = providers_doc["agents"]["providers"]
    lines: list[str] = []
    for pid in provider_ids:
        entry = providers[pid]
        for model in entry["models"]:
            efforts = [f'`"{opt["id"]}"`' for opt in model["thinkingOptions"]]
            effort_text = " or ".join(efforts)
            lines.append(
                f'  - `{pid}/{model["id"]}` with `settings.thinkingOptionId` = {effort_text}'
            )
    return "\n".join(lines)


def render_prompt(role: str, providers_doc: dict, repo_root: Path = REPO_ROOT) -> str:
    raw = (repo_root / "prompts" / f"{role}.md").read_text(encoding="utf-8")
    replacements = {
        "{{LEAD_MENU}}": format_provider_menu(providers_doc, ["agy-lead"]),
        "{{PEER_MENU}}": format_provider_menu(providers_doc, ["agy-peer"]),
    }
    for token, value in replacements.items():
        raw = raw.replace(token, value)
    return raw.rstrip() + "\n"


def render_antigravity_agent(role: str, providers_doc: dict, repo_root: Path = REPO_ROOT) -> str:
    body = render_prompt(role, providers_doc, repo_root)
    return AGENT_FRONTMATTER[role] + body


def render_codex_supervisor_toml(providers_doc: dict, repo_root: Path = REPO_ROOT) -> str:
    overlay_text = (repo_root / "codex" / "supervisor.overlay.toml").read_text(encoding="utf-8")
    prompt_body = render_prompt("supervisor", providers_doc, repo_root)
    if '"""' in prompt_body:
        raise ValueError("Supervisor prompt cannot contain triple double-quotes (TOML multiline delimiter)")

    # Insert developer_instructions before the first TOML table header (`[...]`).
    header = "# Generated by scripts/slp.py build from codex/supervisor.overlay.toml + prompts/supervisor.md.\n"
    table_match = re.search(r"^\[", overlay_text, flags=re.MULTILINE)
    instr_block = f'developer_instructions = """\n{prompt_body}"""\n'
    if table_match:
        prefix = overlay_text[: table_match.start()].rstrip() + "\n"
        suffix = "\n" + overlay_text[table_match.start() :].lstrip()
        rendered = header + prefix + instr_block + suffix
    else:
        rendered = header + overlay_text.rstrip() + "\n" + instr_block

    parsed = tomllib.loads(rendered)
    if parsed.get("developer_instructions") != prompt_body:
        raise ValueError("Rendered codex/supervisor.config.toml round-trip mismatch")
    return rendered


def render_admission_patch(repo_root: Path = REPO_ROOT) -> str:
    patch_path = repo_root / "patches" / "paseo-slp-admission.patch"
    policy_path = repo_root / "patches" / "slp-delegation-policy.js"
    patch_text = patch_path.read_text(encoding="utf-8")
    policy_lines = policy_path.read_text(encoding="utf-8").splitlines()

    marker = "--- a/agent/slp-delegation-policy.js\n"
    idx = patch_text.find(marker)
    if idx == -1:
        raise ValueError("Could not find slp-delegation-policy.js section in paseo-slp-admission.patch")

    prefix = patch_text[:idx]
    hunk_lines = [
        "--- a/agent/slp-delegation-policy.js",
        "+++ b/agent/slp-delegation-policy.js",
        f"@@ -0,0 +1,{len(policy_lines)} @@",
        *[f"+{line}" for line in policy_lines],
    ]
    return prefix + "\n".join(hunk_lines) + "\n"


def expected_generated_files(repo_root: Path = REPO_ROOT) -> dict[Path, str]:
    providers_doc = load_providers(repo_root)
    return {
        repo_root / "antigravity" / "agents" / "slp-supervisor.md": render_antigravity_agent(
            "supervisor", providers_doc, repo_root
        ),
        repo_root / "antigravity" / "agents" / "slp-lead.md": render_antigravity_agent(
            "lead", providers_doc, repo_root
        ),
        repo_root / "antigravity" / "agents" / "slp-peer.md": render_antigravity_agent(
            "peer", providers_doc, repo_root
        ),
        repo_root / "codex" / "supervisor.config.toml": render_codex_supervisor_toml(
            providers_doc, repo_root
        ),
        repo_root / "patches" / "paseo-slp-admission.patch": render_admission_patch(repo_root),
    }


def cmd_build(repo_root: Path = REPO_ROOT) -> int:
    for path, content in expected_generated_files(repo_root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(repo_root)}")
    return 0


def collect_verification_errors(repo_root: Path = REPO_ROOT) -> list[str]:
    errors: list[str] = []

    # 1. Validate providers.json structure.
    providers_doc = load_providers(repo_root)
    providers = providers_doc.get("agents", {}).get("providers", {})
    expected_providers = {"codex-supervisor", "agy-supervisor", "agy-lead", "agy-peer"}
    if set(providers.keys()) != expected_providers:
        errors.append(f"Unexpected provider set: {sorted(providers.keys())}")
    for pid, entry in providers.items():
        models = entry.get("models", [])
        if not models:
            errors.append(f"Provider {pid} has no models")
        for model in models:
            if not model.get("thinkingOptions"):
                errors.append(f"Provider {pid}/{model.get('id')} has no thinkingOptions")

    # 2. Check generated artifacts are up-to-date.
    for path, expected in expected_generated_files(repo_root).items():
        if not path.exists():
            errors.append(f"Missing generated file: {path.relative_to(repo_root)}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(
                f"Out-of-date generated file: {path.relative_to(repo_root)} (run `python3 scripts/slp.py build`)"
            )

    # 3. Check Codex Supervisor TOML parses and matches Antigravity Supervisor body.
    codex_toml = tomllib.loads((repo_root / "codex" / "supervisor.config.toml").read_text(encoding="utf-8"))
    agy_sup = (repo_root / "antigravity" / "agents" / "slp-supervisor.md").read_text(encoding="utf-8")
    agy_body = agy_sup.split("---\n", 2)[2].lstrip()
    if codex_toml.get("developer_instructions") != agy_body:
        errors.append("codex/supervisor.config.toml instructions diverge from antigravity/agents/slp-supervisor.md")

    # 4. Check zero stale provider names in prompts/configs.
    checked_paths = [
        *(repo_root / "prompts").glob("*.md"),
        *(repo_root / "antigravity" / "agents").glob("*.md"),
        repo_root / "codex" / "supervisor.config.toml",
        repo_root / "paseo" / "providers.json",
    ]
    for path in checked_paths:
        text = path.read_text(encoding="utf-8")
        for token in STALE_PROVIDER_TOKENS:
            if token in text:
                errors.append(f"Stale provider reference `{token}` found in {path.relative_to(repo_root)}")

    # 5. Check zero Protocol Leak in Peer prompt.
    for peer_file in (repo_root / "prompts" / "peer.md", repo_root / "antigravity" / "agents" / "slp-peer.md"):
        text = peer_file.read_text(encoding="utf-8")
        for forbidden in FORBIDDEN_PEER_REFS:
            if forbidden in text:
                errors.append(f"Protocol leak `{forbidden}` in {peer_file.relative_to(repo_root)}")

    # 6. Verify all `__SLP_HOME__/shared/...` paths referenced exist in repo.
    ref_pattern = re.compile(r"__SLP_HOME__/(shared/[A-Za-z0-9._/-]+)")
    all_md = [
        *(repo_root / "prompts").glob("*.md"),
        *(repo_root / "antigravity" / "agents").glob("*.md"),
        *(repo_root / "shared").rglob("*.md"),
    ]
    for path in all_md:
        text = path.read_text(encoding="utf-8")
        for rel in ref_pattern.findall(text):
            rel = rel.rstrip(".,;:)")
            if not (repo_root / rel).exists():
                errors.append(f"Broken shared reference `{rel}` in {path.relative_to(repo_root)}")

    # 7. Verify launchers are executable.
    for launcher in (
        repo_root / "codex" / "bin" / "codex-room",
        repo_root / "codex" / "bin" / "codex-room-sync",
    ):
        mode = launcher.stat().st_mode
        if not (mode & stat.S_IXUSR):
            errors.append(f"Launcher is not executable: {launcher.relative_to(repo_root)}")

    return errors


def cmd_verify(repo_root: Path = REPO_ROOT) -> int:
    errors = collect_verification_errors(repo_root)
    if errors:
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        return 1
    print("OK: all SLP configs, prompts, shared references, and patch hunks are consistent.")
    return 0


def cmd_render(args: argparse.Namespace, repo_root: Path = REPO_ROOT) -> int:
    errors = collect_verification_errors(repo_root)
    if errors:
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        return 1

    home_dir = str(Path(args.home).expanduser().resolve())
    node_bin = args.node_bin or shutil.which("node") or "/opt/homebrew/bin/node"
    codex_bin = args.codex_bin or shutil.which("codex") or f"{home_dir}/.local/bin/codex"
    out_dir = Path(args.out).expanduser().resolve()
    if out_dir.exists() and not args.force:
        print(f"ERROR: output directory already exists: {out_dir} (pass --force to overwrite)", file=sys.stderr)
        return 1

    replacements = {
        "__SLP_HOME__": home_dir,
        "__SLP_NODE_BIN__": node_bin,
        "__SLP_CODEX_BIN__": codex_bin,
    }

    copy_map = [
        ("codex/supervisor.config.toml", "codex/supervisor.config.toml"),
        ("codex/bin/codex-room", "bin/codex-room"),
        ("codex/bin/codex-room-sync", "bin/codex-room-sync"),
        ("paseo/providers.json", "paseo/providers.json"),
        ("paseo/mcp/paseo-projects.mjs", "share/slp/paseo-projects.mjs"),
        ("patches/paseo-slp-admission.patch", "patches/paseo-slp-admission.patch"),
    ]
    for src_dir, dst_prefix in (("antigravity/agents", "antigravity/agents"), ("shared", "shared")):
        for path in sorted((repo_root / src_dir).rglob("*")):
            if path.is_file():
                rel = path.relative_to(repo_root / src_dir)
                copy_map.append((str(path.relative_to(repo_root)), f"{dst_prefix}/{rel.as_posix()}"))

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    for src_rel, dst_rel in copy_map:
        src = repo_root / src_rel
        dst = out_dir / dst_rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        text = src.read_text(encoding="utf-8")
        for token, value in replacements.items():
            text = text.replace(token, value)
        if "__SLP_" in text:
            raise ValueError(f"Unresolved placeholder left in rendered {dst_rel}")
        dst.write_text(text, encoding="utf-8")
        if src.stat().st_mode & stat.S_IXUSR:
            dst.chmod(0o755)

    # Validate rendered JSON and TOML.
    json.loads((out_dir / "paseo" / "providers.json").read_text(encoding="utf-8"))
    tomllib.loads((out_dir / "codex" / "supervisor.config.toml").read_text(encoding="utf-8"))

    print(f"Rendered machine bundle to: {out_dir}")
    print(f"  HOME      = {home_dir}")
    print(f"  NODE_BIN  = {node_bin}")
    print(f"  CODEX_BIN = {codex_bin}")
    return 0


def find_paseo_server_dir() -> Path | None:
    paseo_bin = shutil.which("paseo")
    if not paseo_bin:
        return None
    cli_root = Path(os.path.realpath(paseo_bin)).parent.parent
    candidate = cli_root / "node_modules" / "@getpaseo" / "server" / "dist" / "server" / "server"
    return candidate if (candidate / "session.js").exists() else None


def cmd_doctor(repo_root: Path = REPO_ROOT) -> int:
    print("Next-SLP host diagnostics:")
    print(f"  python3 : {sys.executable} ({sys.version.split()[0]})")
    for name in ("bash", "node", "paseo", "agy", "codex"):
        found = shutil.which(name)
        print(f"  {name:<7} : {found or 'NOT FOUND'}")

    server_dir = find_paseo_server_dir()
    print(f"  paseo server dist : {server_dir or 'NOT FOUND'}")
    patch_file = repo_root / "patches" / "paseo-slp-admission.patch"
    if server_dir:
        fwd = subprocess.run(
            ["git", "apply", "--check", str(patch_file)],
            cwd=server_dir,
            capture_output=True,
            text=True,
        )
        rev = subprocess.run(
            ["git", "apply", "--reverse", "--check", str(patch_file)],
            cwd=server_dir,
            capture_output=True,
            text=True,
        )
        if rev.returncode == 0:
            print("  admission patch   : ALREADY APPLIED (matches this patch)")
        elif fwd.returncode == 0:
            print("  admission patch   : READY TO APPLY cleanly")
        else:
            print("  admission patch   : DIFFERS (custom/older patch or different Paseo build)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Next-SLP config builder, verifier, and renderer")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build", help="Regenerate checked-in prompts, TOML, and admission patch from single sources")
    sub.add_parser("verify", help="Verify cross-file consistency and zero drift")
    render_p = sub.add_parser("render", help="Render a machine-ready bundle with resolved paths")
    render_p.add_argument("--out", required=True, help="Output directory for rendered bundle")
    render_p.add_argument("--home", default=str(Path.home()), help="Target machine home directory")
    render_p.add_argument("--node-bin", default="", help="Override node executable path")
    render_p.add_argument("--codex-bin", default="", help="Override codex executable path")
    render_p.add_argument("--force", action="store_true", help="Overwrite existing output directory")
    sub.add_parser("doctor", help="Check local host binaries and Paseo patch status (read-only)")

    args = parser.parse_args()
    if args.command == "build":
        return cmd_build()
    if args.command == "verify":
        return cmd_verify()
    if args.command == "render":
        return cmd_render(args)
    if args.command == "doctor":
        return cmd_doctor()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
